def main() -> None:
    (ROOT / "LICENSE").write_text(LICENSE, encoding="utf-8", newline="\n")
    (ROOT / "CITATION.cff").write_text(
        CITATION.format(today=date.today().isoformat()),
        encoding="utf-8", newline="\n")
    (ROOT / "CONTRIBUTING.md").write_text(CONTRIBUTING, encoding="utf-8", newline="\n")
    (ROOT / "SECURITY.md").write_text(SECURITY, encoding="utf-8", newline="\n")
    wf = ROOT / ".github" / "workflows"
    wf.mkdir(parents=True, exist_ok=True)
    (wf / "ci.yml").write_text(CI, encoding="utf-8", newline="\n")
    (wf / "reproduction.yml").write_text(REPRODUCTION, encoding="utf-8", newline="\n")
    print("wrote LICENSE, CITATION.cff, CONTRIBUTING.md, SECURITY.md, "
          ".github/workflows/{ci,reproduction}.yml")


if __name__ == "__main__":
    main()
