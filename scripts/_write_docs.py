CONTRIBUTING = """# Contributing

## Ground rules

This is a research repository, so the bar is scientific rather than stylistic.

1. **Never loosen a tolerance to make a test pass.** If a numerical test fails,
   find out why. The audit's F3 finding survived to publication because nothing
   ever checked whether the books closed; a test that has been relaxed until it
   is green is worse than no test.
2. **Never delete a failing test that reveals a real problem.** Mark it
   `xfail` with a reason and open an issue.
3. **Never hand-type a number into the manuscript.** All results tables are
   generated by `make tables` and pulled in with `\\input`. CI runs
   `scripts/verify_generated.py` and fails on drift.
4. **`legacy_mode` must stay bit-exact.** `tests/regression/` proves the
   corrected model reproduces `simulation/cdos_sim.py` exactly. If that breaks,
   something changed that nobody decided on.
5. **`simulation/` and `audit/` are frozen.** They are the audited baseline and
   the evidence of what the project looked like before remediation.

## Making a scientific change

Record it in `CHANGELOG.md` and `MEMORY.md` with: the problem, the original
behaviour, the new behaviour, the scientific justification, the files changed,
the tests added, the experiments affected, and the paper sections affected.

## Before opening a pull request

```bash
make lint
make test
make smoke
make tables && make verify
```

## Adding a parameter

Add it to the relevant dataclass in `src/cdos/config.py` with a comment saying
what it is and where it comes from. Never read a constant from inside a model
function — that is what made finding F1 possible.

## Adding an experiment

Add a YAML file to `experiments/`. It must carry an `experiment_id`, a
`description` saying what scientific question it answers, and the `arms` and
`seeds` it needs. An experiment that exists only to increase the count of
experiments should not be added.
"""

